/**
 * Submission Data Models
 * Grounded in Project Bible: Section 4 (Pipeline), Section 9 (DDL: table submission), Section 11 (API).
 */

import type { QualityGrade } from './analysis';

/**
 * Provenance origin of submitted Java code.
 * Bible Constraint: Clients may only submit 'HUMAN', 'AI_GENERATED', or 'AI_ASSISTED'.
 * 'AI_REMEDIATED' is exclusively assigned by the platform verification service.
 */
export type OriginType = 'HUMAN' | 'AI_GENERATED' | 'AI_ASSISTED' | 'AI_REMEDIATED';

/**
 * Core Submission Entity
 * Direct 1:1 mapping to PostgreSQL table `submission` (Bible Section 9).
 */
export interface Submission {
  submissionId: string;
  ownerId: string;
  title: string | null;
  taskId: string | null; // UUID for matched research task pairing (Bible Section 6)
  generationId: string | null; // UUID if generated by platform LLM gateway
  parentSubmissionId: string | null; // UUID for remediation version lineage
  originType: OriginType;
  sourceCode: string;
  contentHash: string; // SHA-256 of normalized source code
  logicalLoc: number; // Non-blank, non-comment lines of code (Bible Section 4)
  createdAt: string; // ISO 8601 timestamp
  deletedAt: string | null;
  provenanceVerified: boolean; // TRUE only when platform itself generated or remediated
}

/**
 * Submission Summary item
 * Returned by GET /api/v1/submissions and Database View `v_run_summary` (Bible Section 9 & 11).
 */
export interface SubmissionSummary {
  submissionId: string;
  title: string | null;
  originType: OriginType;
  logicalLoc: number;
  latestGrade: QualityGrade | null;
  latestScore: number | null;
  createdAt: string;
  provenanceVerified: boolean;
  
  // --- FRONTEND-ONLY PROPOSED FIELDS (for UI list rendering) ---
  findingsCount?: number; // Count of active findings for table view badge
  latestRunId?: string; // Quick reference to latest analysis run
}

/**
 * Request payload for POST /api/v1/submissions
 * Grounded in Project Bible Section 11 API specification.
 */
export interface CreateSubmissionRequest {
  title?: string;
  originType: 'HUMAN' | 'AI_GENERATED' | 'AI_ASSISTED';
  sourceCode: string; // <= 100,000 characters, UTF-8
  taskId?: string;
  autoAnalyze?: boolean; // Extends submit with immediate run (Bible Section 12.1)
}

/**
 * Response payload for POST /api/v1/submissions (HTTP 201 Created)
 */
export interface CreateSubmissionResponse {
  submissionId: string;
  originType: OriginType;
  logicalLoc: number;
  runId?: string; // Present if autoAnalyze = true
}
